#!/usr/bin/env python3
"""Write the coverage table of `device-diagnosis/devices-wanted.md` from the diagnoses.

The pinned diagnosis issue shows that file's top (`diagnosis_issue_body.py`),
coverage table included, so a count typed by hand goes stale on the next
ingest and the issue then asks for devices already read. This rewrites only
the part between the two markers; the wanted list above it stays hand-written,
because what is worth asking for is a judgement, not a count.

**A device counts once, by its stand-in serial**, however many documents it
sent: a machine read twenty times is still one machine, and one read
through its cable and its dongle is one machine too. The rows say what was
seen on any of a device's documents.

    python scripts/generate/generate_devices_wanted.py            # rewrite the table
    python scripts/generate/generate_devices_wanted.py --check    # fail if it is stale
"""

from __future__ import annotations

import argparse
from collections import defaultdict
from collections.abc import Iterable
from dataclasses import dataclass, field
import json
from pathlib import Path
import sys
from typing import Any

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "src"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from generate_firmware_support import NotRead, _decode  # noqa: E402

from sungrow_modbus import DEVICE_TYPES, family_for  # noqa: E402
from sungrow_modbus.battery.power import MODELS as BATTERY_MODELS  # noqa: E402
from sungrow_modbus.diagnosis_document import OUTPUT_TYPES, _battery_word  # noqa: E402
from sungrow_modbus.hybrid_inverter.capabilities import Family  # noqa: E402
from sungrow_modbus.string_inverter import MODELS as SG_MODELS  # noqa: E402

RESULTS = REPO / "device-diagnosis" / "results"
OUTPUT = REPO / "device-diagnosis" / "devices-wanted.md"

START = "<!-- coverage: generated by scripts/generate/generate_devices_wanted.py -->"
END = "<!-- coverage: end -->"

#: What each transport a contributor reports is called in the transport row.
#: `unsure` is absent: it outranks nothing, so the measurement decides.
REPORTED_ROUTES = {
    "direct_lan": "direct LAN",
    "winet_lan": "WiNet-S wired",
    "winet_wlan": "WiNet-S over WiFi",
    "winet": "WiNet-S",
    "logger": "Logger",
}

#: What a measured verdict that starts so is called in the transport row.
VERDICT_ROUTES = (
    ("direct", "direct LAN"),
    ("through a WiNet-S", "WiNet-S"),
    ("through a communication module", "WiNet-S or Logger"),
)


@dataclass
class Inverter:
    """What every document of one inverter, by its stand-in, says together."""

    kind: str
    model: str = ""
    code: int | None = None
    output_types: set[str] = field(default_factory=set)
    firmware: set[str] = field(default_factory=set)
    version_1: set[str] = field(default_factory=set)
    modules: set[str] = field(default_factory=set)
    batteries: set[str] = field(default_factory=set)
    routes: set[str] = field(default_factory=set)
    proxy: bool = False
    capability_test: bool = False


def _documents(folder: str) -> Iterable[dict[str, Any]]:
    for path in sorted((RESULTS / folder).glob("*.json")):
        yield json.loads(path.read_text(encoding="utf-8"))


def _route(document: dict[str, Any]) -> str:
    """Return how one document reached its device, testimony first."""
    said = str((document.get("user_inputs") or {}).get("transport") or "")
    if said in REPORTED_ROUTES:
        return REPORTED_ROUTES[said]
    verdict = str((document.get("connection") or {}).get("verdict") or "")
    for start, name in VERDICT_ROUTES:
        if verdict.startswith(start):
            return name
    return ""


def _code(device: dict[str, Any]) -> int | None:
    raw = str(device.get("device_type_code") or "")
    return int(raw, 16) if raw.startswith("0x") else None


def _version_1(document: dict[str, Any]) -> str:
    try:
        value = _decode(document.get("register_dump") or {}, "sungrow_version_1")
    except (NotRead, KeyError):
        return ""
    return str(value).strip() if value else ""


def inverters() -> dict[str, Inverter]:
    """Return every inverter, hybrid and string, by its stand-in serial."""
    found: dict[str, Inverter] = {}
    for folder, kind in (("inverter", "hybrid"), ("string_inverter", "string")):
        for document in _documents(folder):
            device = document.get("device") or {}
            serial = device.get("serial_anonymized_hashed")
            if not serial:
                continue
            inverter = found.setdefault(serial, Inverter(kind))
            inverter.model = inverter.model or str(device.get("device_type") or "")
            inverter.code = inverter.code or _code(device)
            if device.get("output_type"):
                inverter.output_types.add(str(device["output_type"]))
            if kind == "string":
                continue
            firmware = document.get("firmware") or {}
            if firmware.get("inverter"):
                inverter.firmware.add(str(firmware["inverter"]))
            if version_1 := _version_1(document):
                inverter.version_1.add(version_1)
            module = (document.get("connection") or {}).get(
                "communication_module_firmware"
            )
            if module:
                inverter.modules.add(str(module))
            inverter.batteries.add(_battery_word(document).removeprefix("battery-"))
            if route := _route(document):
                inverter.routes.add(route)
            said = document.get("user_inputs") or {}
            inverter.proxy |= said.get("modbus_proxy") == "yes"
            inverter.capability_test |= bool(
                document.get("capability_test") or document.get("control_test")
            )
    return found


#: Every Sungrow AC wallbox model this project knows a name for, so the
#: coverage row can say what is missing by subtraction rather than by a
#: hand-kept list that goes stale the moment one is read.
WALLBOX_MODELS: tuple[str, ...] = ("AC22E-01", "AC011E-01", "AC007-00")


def wallboxes() -> dict[str, tuple[str, bool]]:
    """Return every wallbox read, by stand-in serial: its model, and how reached.

    A wallbox reached through an inverter's bus is carried in that inverter's
    document, not in one of its own, so counting only `wallbox/` undercounts
    and -- worse -- reports a model as unread after it has been read.
    """
    found: dict[str, tuple[str, bool]] = {}
    for folder in sorted(path.name for path in RESULTS.iterdir() if path.is_dir()):
        for document in _documents(folder):
            section = document.get("wallbox") or {}
            serial = section.get("serial_anonymized_hashed")
            if not serial:
                continue
            model = ((section.get("readings") or {}).get("model_name") or {}).get(
                "value"
            )
            own = folder == "wallbox"
            # Its own document wins: it reaches the wallbox directly and reads
            # every register, where an inverter's bus reads what the dongle
            # forwards.
            if serial not in found or own:
                found[serial] = (str(model or "unknown model"), own)
    return found


def _count(folder: str) -> int:
    return len(list((RESULTS / folder).glob("*.json")))


def _list(values: Iterable[str]) -> str:
    items = sorted(set(values))
    return ", ".join(items) if items else "none"


def _code_list(values: Iterable[str]) -> str:
    items = sorted(set(values))
    return ", ".join(f"`{v}`" for v in items) if items else "none"


def _by_platform(strings: Iterable[str]) -> str:
    """Group `PLATFORM_VERSION` strings under their platform."""
    groups: dict[str, set[str]] = defaultdict(set)
    for value in strings:
        platform, _sep, version = value.partition("_")
        groups[platform].add(version)
    return "; ".join(
        f"{platform} {_code_list(versions)}"
        for platform, versions in sorted(groups.items())
    )


def _by_prefix(modules: Iterable[str]) -> str:
    """Group communication module firmware under everything before `.P`."""
    groups: dict[str, set[str]] = defaultdict(set)
    for value in modules:
        head, sep, tail = value.rpartition(".")
        groups[head if sep else value].add(tail if sep else "")
    return "; ".join(
        f"`{head}` {', '.join(sorted(t for t in tails if t))}"
        for head, tails in sorted(groups.items())
    )


def render_section() -> str:
    """Return the coverage section, markers included."""
    found = inverters()
    hybrids = {s: i for s, i in found.items() if i.kind == "hybrid"}
    strings = {s: i for s, i in found.items() if i.kind == "string"}
    boxes = wallboxes()

    hybrid_models = {i.model for i in hybrids.values() if i.model}
    sg_models = {i.model for i in strings.values() if i.model}
    families = {
        str(family)
        for i in hybrids.values()
        if (family := family_for(i.code)) is not None
    }
    missing_families = sorted(str(f) for f in Family if str(f) not in families)
    outputs = {t for i in found.values() for t in i.output_types}
    missing_outputs = [t for t in OUTPUT_TYPES.values() if t not in outputs]
    batteries = {b for i in hybrids.values() for b in i.batteries}
    sungrow_packs = {m.name for m in BATTERY_MODELS} & {b.upper() for b in batteries}
    missing_packs = sorted({m.name for m in BATTERY_MODELS} - sungrow_packs)
    third_party = sum("thirdparty" in i.batteries for i in hybrids.values())
    routes = {r for i in hybrids.values() for r in i.routes}
    proxies = sum(i.proxy for i in hybrids.values())
    tested = sum(i.capability_test for i in hybrids.values())
    through_logger = sum("Logger" in i.routes for i in hybrids.values())
    ihomemanagers = _count("ihomemanager")
    loggers = _count("logger")

    def plural(n: int, word: str) -> str:
        return f"{n} {word}" if n == 1 else f"{n} {word}s"

    rows = [
        (
            "Hybrid inverter model",
            f"**{len(hybrid_models)} of {len(set(DEVICE_TYPES.values()))}**: "
            + _list(hybrid_models),
            "the other models",
        ),
        ("Product family", _list(families), _list(missing_families)),
        (
            "SG string inverter model",
            f"**{len(sg_models)} of {len(set(SG_MODELS.values()))}**: "
            + _list(sg_models),
            "the other models",
        ),
        (
            "Phase / output type",
            _list(outputs),
            _list(missing_outputs),
        ),
        (
            "Inverter firmware",
            _by_platform(i for h in hybrids.values() for i in h.firmware),
            "any other",
        ),
        (
            "Version 1",
            _by_platform(v for h in hybrids.values() for v in h.version_1),
            "see item 7",
        ),
        (
            "Communication module",
            _by_prefix(m for h in hybrids.values() for m in h.modules),
            "any other",
        ),
        (
            "Sungrow battery",
            _list(sungrow_packs),
            _list(missing_packs),
        ),
        (
            "Third-party battery",
            plural(third_party, "inverter"),
            "other packs",
        ),
        (
            "Transport",
            _list(routes)
            + (
                f"; {plural(proxies, 'inverter')} through a Modbus proxy"
                if proxies
                else ""
            ),
            "any route not listed",
        ),
        (
            "Capability test",
            f"{tested} of {len(hybrids)} hybrid inverters",
            "every other model and firmware",
        ),
        (
            "Wallbox",
            _list(model for model, _ in boxes.values()) if boxes else "none",
            _list(
                model
                for model in WALLBOX_MODELS
                if model not in {read for read, _ in boxes.values()}
            )
            or "none",
        ),
        (
            "iHomeManager",
            # Its document carries no serial, so units cannot be told apart.
            "read" if ihomemanagers else "none",
            "a second unit" if ihomemanagers else "any",
        ),
        (
            "Sungrow Logger",
            ("read" if loggers else "the Logger itself unread")
            + (
                f"; {plural(through_logger, 'inverter')} read through one"
                if through_logger
                else ""
            ),
            "the Logger's own registers" if not loggers else "a second unit",
        ),
    ]
    head = (
        f"{len(found)} inverters, each counted once by its stand-in serial "
        f"however many times it was read: {len(hybrids)} hybrids and "
        f"{len(strings)} SG string inverters. Beside them "
        f"{len(boxes)} {'wallbox' if len(boxes) == 1 else 'wallboxes'} read, "
        f"{sum(1 for _, own in boxes.values() if own)} at "
        f"{'its' if sum(1 for _, own in boxes.values() if own) == 1 else 'their'}"
        " own address and "
        f"{sum(1 for _, own in boxes.values() if not own)} on an inverter's bus"
        f"{', and an iHomeManager' if ihomemanagers else ''}"
        f"{', and a Logger' if loggers else ''}."
    )
    table = ["| Axis | Covered | Missing |", "| --- | --- | --- |"]
    table += [f"| {a} | {b} | {c} |" for a, b, c in rows]
    return "\n".join(
        [
            START,
            "",
            "Generated from [`results/`](results/) by "
            "`scripts/generate/generate_devices_wanted.py`; edit that, not this.",
            "",
            head,
            "",
            *table,
            "",
            END,
        ]
    )


def render() -> str:
    """Return the whole file with its coverage section rewritten."""
    text = OUTPUT.read_text(encoding="utf-8")
    before, start, rest = text.partition(START)
    _old, end, after = rest.partition(END)
    if not start or not end:
        raise SystemExit(f"{OUTPUT.relative_to(REPO)} has lost its coverage markers")
    return before + render_section() + after


def main() -> int:
    """Rewrite the table, or check the committed one is current."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    rendered = render()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != rendered:
            print(
                f"{OUTPUT.relative_to(REPO)}'s coverage table is stale.\n"
                "Run scripts/generate/generate_devices_wanted.py and commit it.",
                file=sys.stderr,
            )
            return 1
        print(f"{OUTPUT.relative_to(REPO)}'s coverage table matches the diagnoses")
        return 0
    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(REPO)}'s coverage table")
    return 0


if __name__ == "__main__":
    sys.exit(main())
